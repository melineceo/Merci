"""Внешний вид главного окна Merci: Material You поверх «жидкого стекла».

Пакет рисует и сообщает о нажатиях — и только. Договор с логикой окна
описан в ``api.py``; настоящая реализация — ``shell.Shell``. Остальные
модули — её части:

* ``style`` — CSS и блок переменных палитры (один провайдер на дисплей);
* ``library`` — стеклянная библиотека слева (в узком окне — рейка);
* ``page`` — герой, плашка, карточки «Сведения» и «Запуск», приёмник APK;
* ``windows`` — раздел «Окна»: «экраны» окон и полоса долгой операции;
* ``container`` — «остров» контейнера в шапке и его панель;
* ``widgets`` — мелкие общие детали;
* ``lang_en_ui`` — английские строки самого вида;
* ``demo`` — учебные данные и снимки состояний (только через договор).

``Shell`` импортируется лениво: ``api`` нужен логике и тестам и без GTK.
"""

from __future__ import annotations


def __getattr__(name: str):
    if name == "Shell":
        from .shell import Shell

        return Shell
    raise AttributeError(name)
